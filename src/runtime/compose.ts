// The local runtime stack: the LibraOS runtime plus its Postgres, run with
// Docker Compose. Pure functions only, so they can be tested without VS Code.

export const COMPOSE_PROJECT = "libraos-vscode";
export const ADMIN_EMAIL = "admin@libraos.local";

// pgvector ≥ 0.8 is required by the runtime's knowledge store. Pinned by
// digest so Docker verifies the bytes it pulls.
export const POSTGRES_IMAGE =
  "pgvector/pgvector:pg16@sha256:7b822b0aac60967beb1ea5e576b8602c94c300a157d187f385ae3e0da199b90a";

// How the runtime container reaches the host.
//   host:   Linux. The runtime shares the host network and binds 127.0.0.1
//           only, so it can call model endpoints on the host's loopback
//           (a local proxy, Ollama) without being reachable from the LAN.
//   bridge: Docker Desktop (macOS, Windows), where host networking is not the
//           default. Loopback model URLs are rewritten to host.docker.internal,
//           which Docker Desktop maps to the host.
export type NetworkMode = "host" | "bridge";

export function networkModeFor(platform: NodeJS.Platform): NetworkMode {
  return platform === "linux" ? "host" : "bridge";
}

// Secrets never appear in this file. Compose reads them from the environment
// of the `docker compose` process, which the extension fills from VS Code
// SecretStorage, so nothing secret is written to disk.
export function composeFile(mode: NetworkMode): string {
  const host = mode === "host";
  const pgHost = host ? "127.0.0.1:${LIBRAOS_PG_PORT:?missing}" : "postgres:5432";
  const pgPorts = host ? '\n    ports: ["127.0.0.1:${LIBRAOS_PG_PORT:?missing}:5432"]' : "";
  const net = host
    ? "    network_mode: host"
    : '    ports: ["127.0.0.1:${LIBRAOS_PORT:-8900}:8900"]\n    extra_hosts: ["host.docker.internal:host-gateway"]';
  const listen = host
    ? "      LIBRA_OS_HOST: 127.0.0.1\n      LIBRA_OS_PORT: ${LIBRAOS_PORT:-8900}\n"
    : "";
  return `# Generated by the LibraOS VS Code extension (${mode} network). Secrets are
# passed in from VS Code SecretStorage when the extension runs docker compose.
name: ${COMPOSE_PROJECT}
services:
  postgres:
    image: ${POSTGRES_IMAGE}
    environment:
      POSTGRES_USER: libraos
      POSTGRES_PASSWORD: \${LIBRAOS_PG_PASSWORD:?missing}
      POSTGRES_DB: libraos${pgPorts}
    volumes: [pgdata:/var/lib/postgresql/data]
    healthcheck:
      test: ["CMD-SHELL", "pg_isready -U libraos"]
      interval: 2s
      retries: 30

  libraos:
    image: \${LIBRAOS_IMAGE:?missing}
    depends_on:
      postgres: { condition: service_healthy }
${net}
    # The runtime refuses to start under Docker's default 64 KiB memlock cap.
    ulimits:
      memlock: { soft: -1, hard: -1 }
    environment:
${listen}      LIBRA_OS_DATABASE_URL: postgresql://libraos:\${LIBRAOS_PG_PASSWORD:?missing}@${pgHost}/libraos?sslmode=disable
      LIBRA_OS_JWT_SECRET: \${LIBRA_OS_JWT_SECRET:?missing}
      LIBRA_OS_ADMIN_EMAIL: \${LIBRA_OS_ADMIN_EMAIL:?missing}
      LIBRA_OS_ADMIN_PASSWORD: \${LIBRA_OS_ADMIN_PASSWORD:?missing}
      LIBRA_OS_PUBLIC_URL: http://localhost:\${LIBRAOS_PORT:-8900}
      OPENAI_API_BASE: \${OPENAI_API_BASE:?missing}
      OPENAI_API_KEY: \${OPENAI_API_KEY:-local}
      OPENAI_MODEL: \${LIBRAOS_MODEL:?missing}
      LIBRA_OS_BRAIN_MODEL: \${LIBRAOS_MODEL:?missing}
      LIBRA_OS_SKILL_MODEL: \${LIBRAOS_MODEL:?missing}
    volumes:
      - documents:/app/data/nova-os/documents

volumes:
  pgdata:
  documents:
`;
}

// The model URL as the runtime container must call it.
export function containerModelUrl(url: string, mode: NetworkMode): string {
  if (mode === "host") return url;
  return url.replace(/^(https?:\/\/)(localhost|127\.0\.0\.1|\[::1\])(?=[:/]|$)/, "$1host.docker.internal");
}

export interface RuntimeSecrets {
  pgPassword: string;
  jwtSecret: string;
  adminPassword: string;
}

export interface RuntimeSettings {
  image: string;
  port: number;
  // Postgres's loopback port in host mode.
  pgPort: number;
  mode: NetworkMode;
  modelBaseUrl: string;
  modelName: string;
  modelApiKey?: string;
}

// The environment for every `docker compose` call. Compose interpolates the
// file from it, so every command (up, down, logs, pull) needs the same values.
export function composeEnv(s: RuntimeSettings, sec: RuntimeSecrets): Record<string, string> {
  return {
    LIBRAOS_IMAGE: s.image,
    LIBRAOS_PORT: String(s.port),
    LIBRAOS_PG_PORT: String(s.pgPort),
    LIBRAOS_PG_PASSWORD: sec.pgPassword,
    LIBRA_OS_JWT_SECRET: sec.jwtSecret,
    LIBRA_OS_ADMIN_EMAIL: ADMIN_EMAIL,
    LIBRA_OS_ADMIN_PASSWORD: sec.adminPassword,
    OPENAI_API_BASE: containerModelUrl(s.modelBaseUrl, s.mode),
    OPENAI_API_KEY: s.modelApiKey || "local",
    LIBRAOS_MODEL: s.modelName,
  };
}

// Arguments for `docker compose` against the generated file.
export function composeArgs(file: string, ...cmd: string[]): string[] {
  return ["compose", "-f", file, "-p", COMPOSE_PROJECT, ...cmd];
}

export function isDigestPinned(image: string): boolean {
  return /@sha256:[0-9a-f]{64}$/.test(image);
}

// Hex only: the Postgres password is embedded in a connection URL.
export function randomSecret(bytes: number, rand: (n: number) => Buffer): string {
  return rand(bytes).toString("hex");
}
